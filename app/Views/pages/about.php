<div class="card">
    <h1>About This Project</h1>
    <p>
        This project is a laboratory activity for building the first version of a
        basic Point-of-Sale (POS) system using the <strong>CodeIgniter 4</strong> PHP framework.
    </p>
    <h2>Current Scope</h2>
    <ul>
        <li>A landing page and an about page</li>
        <li>A Customer Accounts page listing customer records (full name, email, phone)</li>
        <li>A User Accounts page listing user/staff records (username, full name, role)</li>
        <li>Data for the Customer and User Accounts pages currently comes from static
            PHP arrays defined in their respective controllers, since no database has
            been connected yet</li>
    </ul>
    <h2>Planned Next Steps</h2>
    <ul>
        <li>Replace the static arrays with a real database (MySQL) using CodeIgniter's
            Query Builder / Models</li>
        <li>Add create, update, and delete functionality for customers and users</li>
        <li>Add authentication for staff accounts</li>
    </ul>
</div>
